function getIsoTransliteration(telugu: string): string {
  if (TELUGU_ISO15919_MAP[telugu]) return TELUGU_ISO15919_MAP[telugu];
  for (const [k, v] of Object.entries(TELUGU_ISO15919_MAP)) {
    if (telugu.includes(k)) return v;
  }
  return telugu.toLowerCase().replace(/[^a-z0-9]/g, '');
}

